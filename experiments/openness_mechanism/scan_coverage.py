"""Measure multiscale occupied-cell volume on the saved openness branches."""

import argparse
from concurrent.futures import ProcessPoolExecutor
import csv
import json
from pathlib import Path
import pickle

from experiments.openness_mechanism.run import (
    RULES, InterventionHPPSO, continue_branches, BatchBudget, BatchFunction, trait_suite,
)
from experiments.final_benchmark import read_result
import numpy as np


def cell_ids(points, width, offset):
    """Exact cell identity as a packed integer vector, with no hash collisions."""
    coordinates = np.ascontiguousarray(np.floor(points / width + offset), dtype=np.int32)
    return coordinates.view(np.dtype((np.void, coordinates.dtype.itemsize * coordinates.shape[-1]))).ravel()


def coverage(initial, trace, focal, widths, offsets):
    for width in widths:
        all_counts = np.zeros((len(RULES), len(offsets), 4), dtype=int)
        for i, offset in enumerate(offsets):
            initial_ids = cell_ids(initial, width, offset)
            initial_unique = np.unique(initial_ids)
            visited_by_rule = []
            for j, positions in enumerate(trace):
                cells = cell_ids(positions, width, offset).reshape(positions.shape[:2])
                visited = np.unique(cells)
                swarm_cells = np.union1d(initial_unique, visited)
                focal_cells = np.unique(np.r_[initial_ids[focal:focal+1], cells[:, focal]])
                new_vs_start = len(swarm_cells) - len(initial_unique)
                all_counts[j, i, :3] = len(swarm_cells), new_vs_start, len(focal_cells)
                visited_by_rule.append(swarm_cells)
            for j, visited in enumerate(visited_by_rule[:-1]):
                all_counts[j, i, 3] = len(np.setdiff1d(visited, visited_by_rule[-1], assume_unique=True))
        means = all_counts.mean(axis=1)
        for j, rule in enumerate(RULES):
            swarm, new, focal_count, exclusive = means[j]
            yield dict(rule=rule, cell_width=width, swarm_cells=swarm, new_cells=new,
                       focal_cells=focal_count, cells_outside_control=exclusive,
                       log10_volume=np.log10(swarm) + initial.shape[-1] * np.log10(width))


def replay(path, source_cfg, settings, spec, cfg, offsets):
    archive = read_result(path)
    if not archive['snapshots']:
        return [], 0
    with path.with_suffix('.pkl').open('rb') as stream:
        snapshots = pickle.load(stream)  # trusted local checkpoints generated by run.py
    name, seed = archive['function'], archive['seed']
    problem = trait_suite(source_cfg['dimension'], settings['instance_seed'])[name]
    objective = BatchFunction(problem)
    population, dimension = source_cfg['population'], source_cfg['dimension']
    draws = []

    def record_position(points):
        draws.append(points.copy())
        return objective(points)

    # The constructor only loads cached scores. continue_branches restores the checkpoint.
    cached = snapshots[0]['state']['scores']
    tracker = BatchBudget(lambda _: cached.copy(), population, 1, dimension, 1)
    engine = InterventionHPPSO(tracker, problem['bounds'], population, seed, [spec], settings)
    tracker.function = record_position
    active = engine.width > 0
    rows = []
    for saved in snapshots:
        draws.clear()
        for key, value in saved['state'].items():
            setattr(engine, key, value)
        branch = continue_branches(engine, saved, source_cfg['horizon'], source_cfg['recovery_threshold'])
        expected = [r for r in archive['outcomes'] if r['update'] == saved['update']]
        if branch != expected:
            raise ValueError(f'Replayed branches differ at {name}, seed {seed}, update {saved["update"]}')
        trace = np.stack(draws, axis=1)
        assert trace.shape == (len(RULES), source_cfg['horizon'], population, dimension)
        initial = saved['state']['positions'][0][:, active]
        lower, width = engine.lower[active], engine.width[active]
        normalized = (trace[..., active] - lower) / width
        for row in coverage((initial - lower) / width, normalized, saved['focal'],
                            cfg['relative_cell_widths'], offsets[:, active]):
            rows.append(dict(function=name, seed=seed, update=saved['update'],
                             active_dimensions=int(active.sum()), **row))
    return rows, len(snapshots) * len(RULES) * source_cfg['horizon'] * population


def report(rows, evaluations, cfg, source_cfg, names, output):
    import pandas as pd
    import matplotlib
    matplotlib.use('Agg')
    import matplotlib.pyplot as plt
    from experiments.openness_mechanism.analyze import COLORS, LABELS, contrasts

    data = pd.DataFrame(rows)
    data.to_csv(output / 'snapshot_coverage.csv', index=False)
    metrics = ['swarm_cells', 'new_cells', 'focal_cells', 'cells_outside_control']
    seed = data.groupby(['function', 'seed', 'cell_width', 'rule'], sort=False)[metrics].mean().reset_index()
    seed.to_csv(output / 'coverage_by_seed.csv', index=False)
    summary = seed.groupby(['function', 'cell_width', 'rule'], sort=False)[metrics].mean().reset_index()
    maxima = data.groupby(['function', 'cell_width', 'rule']).swarm_cells.max().rename('max_snapshot_swarm_cells')
    summary = summary.join(maxima, on=['function', 'cell_width', 'rule'])
    summary.to_csv(output / 'coverage_summary.csv', index=False)
    overall = summary.groupby(['cell_width', 'rule'], sort=False)[metrics].mean().reset_index()
    overall.to_csv(output / 'fixed_suite_means.csv', index=False)
    width = cfg['reference_cell_width']
    reference = seed.loc[seed.cell_width.eq(width)]
    tests = contrasts(reference, ['swarm_cells', 'focal_cells'], RULES[1:], source_cfg)
    # One seed cannot estimate between-seed uncertainty.
    tests.loc[tests.n_seeds.lt(2), ['ci95_low', 'ci95_high', 'p_exact', 'p_holm']] = np.nan
    tests.to_csv(output / 'paired_reference_width.csv', index=False)

    fig, axes = plt.subplots(2, 2, figsize=(10, 7), layout='constrained')
    for ax, function in zip(axes.flat, source_cfg['functions'], strict=True):
        for rule in RULES:
            series = summary.loc[summary.function.eq(function) & summary.rule.eq(rule)].sort_values('cell_width')
            ax.plot(series.cell_width, series.swarm_cells, 'o-', ms=4, label=LABELS[rule], color=COLORS[rule])
        if not summary.function.eq(function).any():
            ax.text(.5, .5, 'No eligible stagnation snapshots', transform=ax.transAxes, ha='center')
        ax.set_xscale('log')
        ax.axvline(width, color='#aaa', lw=.8, ls='--')
        ax.grid(axis='y', alpha=.25)
        ax.set_title(names[function], loc='left', fontweight='bold')
    handles, labels = axes.flat[0].get_legend_handles_labels()
    fig.legend(handles, labels, loc='outside lower center', ncols=4, frameon=False)
    fig.suptitle(f'Search space coverage after {source_cfg["horizon"]} updates · {source_cfg["dimension"]}D', fontweight='bold')
    fig.supylabel('Distinct cells visited (seed-averaged)')
    for ax in axes[-1]:
        ax.set_xlabel('Cell width (fraction of search interval)')
    fig.savefig(output / 'coverage_by_scale.pdf')
    fig.savefig(output / 'coverage_by_scale.png', dpi=180)
    plt.close(fig)

    ref = summary.loc[summary.cell_width.eq(width)]
    suite = overall.loc[overall.cell_width.eq(width)].set_index('rule')
    literal_max = data.loc[data.cell_width.eq(width), 'swarm_cells'].max()
    out = [
        f'# Scanned search-space hypervolume at {source_cfg["dimension"]}D',
        'Each branch starts from the same saved swarm and visits 500 evaluated positions over ten updates. '
        'We include the 50 shared starting positions and count unique occupied cells after normalizing coordinates '
        'by their search widths. Each cell has volume $w^d$ in normalized coordinates. The reported proxy is '
        '$N_{\\mathrm{cells}}w^d$, averaged over 16 common grid offsets. It counts finite-resolution visits '
        'and does not assume that segments between evaluated points were explored. The grid is not clipped at the domain boundary.',
        'Only occupied cells are stored. Integer coordinate tuples are packed as bytes and deduplicated exactly. '
        'Thus storage scales with the number of points and dimensions, rather than with the size of the full grid. '
        'Focal-particle coverage and cells outside the no-attraction branch are available in the data tables.',
        f'## Results at the reference cell width ({width:g} of each coordinate range)',
        '| Function | Worse peer | Better peer | Random peer | No attraction |',
        '|---|---:|---:|---:|---:|',
    ]
    for function in source_cfg['functions']:
        series = ref.loc[ref.function.eq(function)].set_index('rule').swarm_cells.reindex(RULES)
        if series.isna().all():
            out.append(f'| {names[function]} | — | — | — | — |')
            continue
        out.append(f'| {names[function]} | ' + ' | '.join(f'{series[rule]:.3f}' for rule in RULES) + ' |')
    out.append('| Equal-weight mean across functions | ' + ' | '.join(f'{suite.loc[r,"swarm_cells"]:.3f}' for r in RULES) + ' |')
    winners = suite.index[suite.swarm_cells.eq(suite.swarm_cells.max())].tolist()
    out.append(f'At the reference width, {", ".join(LABELS[r] for r in winners)} had the largest equal-weight '
               f'mean, {suite.swarm_cells.max():.3f} cells. The largest single snapshot covered '
               f'{literal_max:.3f} cells on average across grid offsets.')
    out.append('### Resolution check')
    out.append('| Relative width | Largest equal-weight mean | Mean occupied cells |')
    out.append('|---:|---|---:|')
    for scale, frame in overall.groupby('cell_width'):
        best = frame.loc[frame.swarm_cells.eq(frame.swarm_cells.max())]
        out.append(f'| {scale:g} | {", ".join(LABELS[r] for r in best.rule)} | {best.swarm_cells.iloc[0]:.3f} |')
    out.extend([
        'Volumes are comparable across rules at the same width. Larger cells mechanically inflate the volume '
        'at coarser widths, so the resolution check compares rules within each width. Snapshots are first averaged '
        'within each contributing seed and then across seeds for each function. The suite summary equally weights functions with snapshots. '
        'The paired table applies Holm correction separately to swarm and focal coverage at the reference width. '
        'Functions with only one contributing seed are reported descriptively.',
        f'Replayed {data[["function","seed","update"]].drop_duplicates().shape[0]} saved snapshots. '
        f'The branch replays used {evaluations:,} objective evaluations and reproduced the archived outcomes exactly.',
        '## Reproduce\n\n```powershell\n$env:PYTHONPATH = "$PWD\\src"\n'
        + ('python -m experiments.openness_mechanism.run --config experiments/openness_mechanism/config_1000d.json '
         '--output experiments/openness_mechanism/results_1000d --workers 3\n'
         'python -m experiments.openness_mechanism.scan_coverage --source experiments/openness_mechanism/results_1000d '
         '--output experiments/openness_mechanism/coverage_results_1000d' if source_cfg['dimension'] == 1000 else
         'python -m experiments.openness_mechanism.scan_coverage') + '\n```',
    ])
    (output / 'README.md').write_text('\n\n'.join(out[:5]) + '\n' + '\n'.join(out[5:11])
                                     + '\n\n' + '\n\n'.join(out[11:]), encoding='utf-8')
    print(overall.to_string(index=False))
    print(f'{evaluations:,} branch evaluations')


def main():
    base = Path(__file__).resolve().parent
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--source', type=Path, default=base / 'results')
    parser.add_argument('--config', type=Path, default=base / 'coverage_config.json')
    parser.add_argument('--output', type=Path, default=base / 'coverage_results')
    args = parser.parse_args()
    cfg = json.loads(args.config.read_text())
    plan = json.loads((args.source / 'plan.json').read_text())
    source_cfg, settings = plan['config'], plan['settings']
    reference = json.loads((Path(source_cfg['reference']) / 'plan.json').read_text())
    if reference['fingerprint'] != plan['reference_fingerprint']:
        raise ValueError('Snapshot reference fingerprint differs')
    spec = reference['protocol']['variants'][reference['protocol']['factorial']['15']]['spec']
    offsets = np.random.default_rng(cfg['grid_seed']).random((cfg['grid_offsets'], source_cfg['dimension']))
    args.output.mkdir(parents=True, exist_ok=True)
    files = [args.source / 'trials' / f / f'seed_{seed:03d}.json.gz'
             for f in source_cfg['functions'] for seed in source_cfg['seeds']]
    coverage_fields = ('function', 'seed', 'snapshots', 'stagnant_states', 'eligible_stagnant_states',
                       'replay_evaluations', 'branch_evaluations')
    counts = []
    for path in files:
        trial = read_result(path)
        if trial['fingerprint'] != plan['fingerprint'] or trial['replay_evaluations'] != source_cfg['budget']:
            raise ValueError(f'Invalid saved trial: {path}')
        counts.append({key: trial[key] for key in coverage_fields})
    with (args.output / 'stagnation_coverage.csv').open('w', newline='', encoding='utf-8') as stream:
        writer = csv.DictWriter(stream, fieldnames=coverage_fields)
        writer.writeheader()
        writer.writerows(counts)
    rows, evaluations = [], 0
    with ProcessPoolExecutor(max_workers=cfg['workers']) as pool:
        pending = [pool.submit(replay, path, source_cfg, settings, spec, cfg, offsets) for path in files]
        for i, future in enumerate(pending, 1):
            batch, count = future.result()
            rows.extend(batch)
            evaluations += count
            print(f'[{i}/{len(files)}] saved run processed', flush=True)
    if not rows:
        total = sum(row['replay_evaluations'] for row in counts)
        (args.output / 'README.md').write_text(
            f'# Scanned search-space hypervolume at {source_cfg["dimension"]}D\n\n'
            f'The {len(counts)} runs consumed {total:,} objective evaluations and yielded no eligible '
            'stagnation snapshots. No counterfactual hypervolume estimate is available. '
            'See [coverage by function and seed](stagnation_coverage.csv).\n', encoding='utf-8')
        return
    if evaluations != sum(row['branch_evaluations'] for row in counts):
        raise ValueError('Coverage replay evaluation count differs from the source experiment')
    report(rows, evaluations, cfg, source_cfg, settings['function_display_names'], args.output)


if __name__ == '__main__':
    main()
